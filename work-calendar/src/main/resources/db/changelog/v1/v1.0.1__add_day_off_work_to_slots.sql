-- =====================================================================
-- work-calendar: добавление флага «работа в выходной» в слоты
-- =====================================================================
-- is_day_off_work = TRUE, если сотрудник работал в свой выходной
-- (по графику 2/2, 3/3 и т.п.). Устанавливается вручную менеджером.
-- Учитывается в отчёте по часам отдельной колонкой.
-- =====================================================================

ALTER TABLE shift_slots
    ADD COLUMN IF NOT EXISTS is_day_off_work BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN shift_slots.is_day_off_work IS 'TRUE — сотрудник работал в свой выходной (ручной флаг)';